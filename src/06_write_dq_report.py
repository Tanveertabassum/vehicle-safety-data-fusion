"""Step 6 - write reports/DATA_QUALITY.md.

Every number in the report is read from the JSON files the pipeline wrote; nothing is typed by hand.
"""
import json

import pandas as pd

from common import PROCESSED, REPORTS, ROOT


def load(name):
    return json.loads((REPORTS / name).read_text())


def f(n):
    return f"{n:,}" if isinstance(n, int) else str(n)


def main():
    ing, dq, vt = load("ingest_summary.json"), load("dq_metrics.json"), load("vehicle_table_stats.json")
    c, r, e, lk = dq["complaints"], dq["recalls"], dq["epa"], dq["linking"]
    comp, inc, aft = c["completeness_raw"], c["inconsistent_values_raw"], c["after_cleaning"]
    L = lk["complaints"]["match_rate_pct_cumulative"]
    ub = lk["complaints_unlinked_breakdown"]
    total = c["raw_rows"]
    vtab = pd.read_parquet(PROCESSED / "vehicle_model_table.parquet")
    no_displ = vtab.displ_median.isna()
    no_displ_ev = int((vtab[no_displ].share_ev > 0).sum())
    cm = pd.read_parquet(PROCESSED / "complaints_clean.parquet", columns=["MAKE_N", "BASE_N"])
    epa_makes = set(pd.read_parquet(PROCESSED / "epa_base_models.parquet").MAKE_N)
    top_noepa = cm[cm.BASE_N.isna() & ~cm.MAKE_N.isin(epa_makes)].MAKE_N.value_counts().head(8)

    md = f"""# Data-quality report

All figures below are generated by `src/06_write_dq_report.py` from the JSON files written by the
pipeline (`reports/dq_metrics.json`, `reports/ingest_summary.json`, `reports/vehicle_table_stats.json`).
They describe the exact raw files listed in the README (SHA-256 verified on ingest:
{sum(v['matches_expected'] for v in ing['hashes'].values())}/{len(ing['hashes'])} files matched).

## 1. What came in

| Source | Format | Rows | Columns | Grain |
|---|---|---|---|---|
| NHTSA complaints 2020-2026 | headerless TAB-delimited text in ZIP, UTF-8, names from data dictionary | {f(ing['complaints']['rows'])} | {ing['complaints']['columns']} | one row per complaint x component |
| NHTSA recall documents 2020-2026 | quoted CSV with header in ZIP | {f(ing['recalls']['rows'])} | {ing['recalls']['columns']} | one row per recall *document* x vehicle |
| EPA fuel-economy table | wide CSV | {f(ing['epa']['rows'])} | {ing['epa']['columns']} | one row per tested configuration (model years {e['model_year_range'][0]}-{e['model_year_range'][1]}) |

The three sources describe a vehicle at three different granularities, and none shares an ID with
another. The only common key is the text triple (make, model, model year), which is spelled
differently in every source. That mismatch is the central data-quality problem of this project.

## 2. Completeness

**Complaints (raw, {f(total)} rows)**

| Field | Blank | Blank % | Note |
|---|---|---|---|
| Make / model | {f(comp['MAKETXT']['blank'])} / {f(comp['MODELTXT']['blank'])} | {comp['MAKETXT']['blank_pct']} | |
| Model year | {f(comp['YEARTXT']['blank'])} | {comp['YEARTXT']['blank_pct']} | plus {f(comp['YEARTXT']['unknown_9999'])} coded `9999` (unknown) |
| Component | {f(comp['COMPDESC']['blank'])} | {comp['COMPDESC']['blank_pct']} | |
| Narrative text | {f(comp['CDESCR']['blank'])} | {comp['CDESCR']['blank_pct']} | |
| VIN (11 chars) | {f(comp['VIN']['blank'])} | {comp['VIN']['blank_pct']} | |
| Mileage | {f(comp['MILES']['blank'])} | {comp['MILES']['blank_pct']} | plus {f(comp['MILES']['zero'])} zeros. NHTSA's dictionary says blanks became 0 in 2021; this file still has blanks |
| Drive train | {f(comp['DRIVE_TRAIN']['blank'])} | {comp['DRIVE_TRAIN']['blank_pct']} | effectively unusable |
| Fuel type | {f(comp['FUEL_TYPE']['blank'])} | {comp['FUEL_TYPE']['blank_pct']} | effectively unusable |
| Cylinders | {f(comp['NUM_CYLS']['blank'])} | {comp['NUM_CYLS']['blank_pct']} | effectively unusable |
| Transmission | {f(comp['TRANS_TYPE']['blank'])} | {comp['TRANS_TYPE']['blank_pct']} | effectively unusable |

The vehicle-specification fields inside the complaint file are 95-100% empty. This is the main
reason a separate specification source (EPA) is needed at all.

**Recalls** had no blank values in its 5 content columns, but {f(r['model_year_unknown_9999'])} rows
use model year `9999` (equipment or unknown).

**EPA**: drive is missing in {f(e['completeness_raw']['drive'])} rows and cylinders in
{f(e['completeness_raw']['cylinders'])}. Of the missing cylinder values, {f(e['cylinders_missing_and_electric'])} belong
to electric vehicles, where the field does not apply, and only {f(e['cylinders_missing_not_electric'])} are
genuinely missing. `atvType` ({f(e['completeness_raw']['atvType'])} blank) and `tCharger`
({f(e['completeness_raw']['tCharger'])} blank) are blank *by design*: blank means "conventional fuel"
and "not turbocharged". They are encoded as 0/1 flags rather than treated as missing.

## 3. Duplicates

| Check | Result |
|---|---|
| Complaints: exact duplicate rows | {f(c['dup_exact_rows'])} |
| Complaints: duplicate internal record ID (CMPLID) | {f(c['dup_cmplid'])} |
| Complaints: rows belonging to multi-component complaints | {f(c['rows_from_multi_component_complaints'])} of {f(total)}; only {f(c['raw_unique_complaints_odino'])} distinct complaints (ODINO) |
| Complaints: same vehicle + identical narrative filed under a new complaint number | **{f(c['resubmitted_complaints_removed'])} removed** |
| Recalls: exact duplicate rows | **{f(r['dup_exact_rows'])} removed** |
| Recalls: documents per campaign | median {r['docs_per_campaign_median']:.0f}, max {f(r['docs_per_campaign_max'])}, collapsed to one row per campaign x vehicle |
| EPA: exact duplicate rows / duplicate IDs | {f(e['dup_exact_rows'])} / {f(e['dup_id'])} |
| EPA: several configurations per (make, base model, year) | {f(e['dup_make_basemodel_year_configs'])} rows. Intended (one row per engine/transmission), aggregated to {f(e['after_cleaning']['base_model_year_rows'])} base-model-years (2005+) |

The multi-component structure is not an error, but counting rows instead of complaints would inflate
every complaint statistic by about {round(total / c['raw_unique_complaints_odino'], 2)}x. All counts in this project are distinct complaints.

## 4. Inconsistent and invalid values (complaints, vehicle rows)

| Issue | Rows before | After fix | Fix |
|---|---|---|---|
| Model year `9999` | {f(inc['model_year_unknown_9999'])} | {f(aft['model_year_missing'])} set to missing | cannot be linked; excluded from joins |
| Failure date after the date NHTSA received the complaint | {f(inc['failure_after_received_date'])} | set to missing | impossible |
| Failure date before 1990 | {f(inc['failure_before_1990'])} | set to missing | implausible for 2020+ filings |
| | | total failure dates missing/invalid after fix: {f(aft['fail_date_missing_or_invalid'])} | |
| Failure more than 1 year before the model year | {f(inc['failure_more_than_1y_before_model_year'])} | flagged, kept | could be a typo in year or date; no safe correction |
| Mileage above 500,000 | {f(inc['miles_over_500k'])} | set to missing; 0 also treated as "not given" | usable mileage values: {f(aft['miles_usable'])} |
| State not a valid US/territory/military postal code | {f(inc['state_not_valid_postal_code'])} | {f(aft['state_missing_or_invalid'])} set to missing | military (AA/AE/AP) and freely-associated states (FM/PW/MH) are counted as *valid* |
| Model text with data-entry prefix "redundant" (e.g. "redundant SIENNA") | {f(inc['model_redundant_prefix'])} | {f(aft['model_redundant_prefix'])} | prefix stripped |
| Make spellings (e.g. {", ".join(f'"{k}" ({v})' for k, v in inc['make_mercedes_variants'].items())}) | {f(inc['make_spellings_raw'])} distinct | {f(inc['make_spellings_after_normalisation'])} | upper-case, remove punctuation/spaces |
| Component labels: NHTSA's old and new taxonomies mixed (e.g. "ENGINE" vs "ENGINE AND ENGINE COOLING", "SERVICE BRAKES" vs "SERVICE BRAKES, HYDRAULIC") | {f(inc['component_top_level_labels_raw'])} top-level labels | {f(aft['component_groups'])} groups | explicit mapping in `src/common.py` |

**Text encoding.** The complaint file is UTF-8 (every line decodes as UTF-8). {f(inc['narratives_with_non_ascii_chars'])} narratives
contain non-ASCII characters such as curly quotes or "…". A first version of the pipeline read the file as Latin-1, which turned these
into garbage like "moduleâ¦". The fix was to read it as UTF-8; garbled sequences remaining after the fix: {f(inc['narratives_with_mojibake_after_utf8_read'])}.

**Recalls:** {f(r['campaign_id_nonstandard_rows'])} rows ({f(r['campaign_id_nonstandard_campaigns'])} campaigns) have IDs that do
not follow the usual `YYV###` pattern (e.g. `21V00A`). They were kept, and the filing year was still read from the first two digits.
Make spellings went from {f(r['make_spellings_raw'])} to {f(r['after_cleaning']['make_spellings'])} after normalisation and after keeping vehicle campaigns only.

## 5. Integration: linking complaints and recalls to EPA specifications

| Step | Complaint rows linked (cumulative) |
|---|---|
| Naive exact string join on (make, model, year) | **{lk['complaints_naive_exact_string_match_pct']}%** |
| Same, case-insensitive | {lk['complaints_case_insensitive_exact_string_match_pct']}% |
| 1. Normalised exact match on EPA base model | {L['1_exact_base_model']}% |
| 2. + match on EPA trim name, or one half of combined names like "Legacy/Outback" | {L['2_exact_trim_or_alias']}% |
| 3. + strip repeated make ("MAZDA3" -> "3") | {L['3_make_prefix_removed']}% |
| 4. + longest EPA base model that prefixes the NHTSA model ("SILVERADO1500" -> "SILVERADO") | {L['4_prefix_match']}% |
| 5. + NHTSA model prefixes trims of exactly one EPA base model ("GLE450" -> "GLE-Class") | **{L['5_trim_prefix_match']}%** |

Fuzzy rules create false links, so two guards were added after spot checks found real errors:

* **Heavy-duty guard.** EPA does not test heavy-duty pickups and vans. A prefix match onto an EPA pickup or van
  is refused when the remainder is 2500/3500/HD/SD and similar. Blocked, for example: {", ".join(lk['top_heavy_duty_blocked'][:4])}.
* **Different-vehicle guard.** A remainder like EV, LIGHTNING, CONNECT or CITY is refused. Before this guard,
  a petrol F-150 was linked to the electric F-150 Lightning, and a Transit van to the much smaller Transit Connect.

Most frequent fuzzy links, kept after review: {"; ".join(lk['top_prefix_matches'][:8])}.

Still unlinked: {f(ub['total'])} complaint rows. Of these (categories can overlap), {f(ub['make_not_in_epa'])} are makes EPA does not cover
(largest: {", ".join(f"{k} ({v})" for k, v in top_noepa.items())}: RVs, trailers, motorcycles, heavy trucks), {f(ub['heavy_duty_blocked'])} were blocked by the heavy-duty guard, and {f(ub['model_year_after_epa_snapshot_or_partial'])} have
model year {ub['epa_snapshot_last_model_year']}+, where the EPA snapshot is partial or absent. The largest remaining groups:
{", ".join(lk['top_unmatched'][:6])}. The largest of these are heavy-duty trucks (F-250/350, Ram 2500/3500) that EPA does not test.

**Recalls:** only {lk['recall_campaign_vehicles']['match_rate_pct_cumulative']['5_trim_prefix_match']}% of all campaign-vehicle rows link,
because the recall file also covers trucks, buses, trailers and RVs. Restricted to makes EPA covers and model years
before {ub['epa_snapshot_last_model_year']}, {lk['recalls_in_scope']['linked_among_those_pct']}% of
{f(lk['recalls_in_scope']['rows_with_epa_make_and_model_year_before_snapshot_end'])} rows link.

## 6. Resulting modelling table

{f(vt['rows'])} vehicles (EPA make x base model x model year, 2015-2022), {f(vt['nameplates'])} nameplates, {f(vt['makes'])} makes.
{f(vt['positives'])} ({vt['positive_rate_pct']}%) had a new vehicle recall campaign filed in 2023 or later.
{f(vt['rows_with_zero_complaints'])} vehicles had no linked complaints in the feature window; these are kept as genuine zeros.
{f(vt['complaints_used_in_features'])} distinct complaints feed the features. Engine size is missing for
{f(int(no_displ.sum()))} vehicles, {no_displ_ev} of which have electric configurations. The model imputes the median and also gets an explicit EV-share feature.

## 7. Known residual issues

* Complaints are unverified consumer reports, and a vehicle's complaint volume also reflects how many were sold.
  Sales data is not public, so EPA configuration count is only a weak proxy.
* Prefix links like "SANTA FE SPORT" -> "SANTA FE" attach a related, not identical, vehicle's specifications.
* The 2025 recall documents look incomplete: {r['after_cleaning']['campaigns_by_filed_year'].get('2025', 0)} campaigns, versus
  {min(v for k, v in r['after_cleaning']['campaigns_by_filed_year'].items() if k != '2025')}-{max(r['after_cleaning']['campaigns_by_filed_year'].values())} in other years,
  probably because documents lag behind filings. Some 2025 recalls may therefore be missing from the label.
* The model-year/failure-date conflicts ({f(inc['failure_more_than_1y_before_model_year'])} rows) were flagged but not corrected.
"""
    (REPORTS / "DATA_QUALITY.md").write_text(md)
    print("wrote", REPORTS / "DATA_QUALITY.md")


if __name__ == "__main__":
    main()
